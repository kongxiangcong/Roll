import {expect,test} from '@playwright/test';

test('daily settings fold maintenance and select saved material and review while research remains ungranted',async({page})=>{
  const failures:string[]=[];page.on('pageerror',e=>failures.push(String(e)));page.on('response',r=>{if(r.status()>=500)failures.push(`${r.status()} ${r.url()}`);});
  await page.goto('/');
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await expect(page.getByText('交易判断未启用',{exact:true}).first()).toBeVisible();
  const fold=page.locator('details').filter({has:page.getByText('模型维护与资格核验',{exact:true})});
  await expect(fold).toHaveCount(1);
  await expect(fold).not.toHaveAttribute('open','');
  await expect(page.getByRole('heading',{name:'维护检查点',exact:true})).not.toBeVisible();
  await fold.locator('summary').first().click();
  await expect(page.getByRole('heading',{name:'维护检查点',exact:true})).toBeVisible();
  const materials=await(await page.request.get('/api/research/review-materials')).json();
  expect(materials).toHaveLength(2);
  const material=materials[1];
  await page.getByLabel('已保存的冻结审阅材料').selectOption(material.material_id);
  await expect(page.getByRole('button',{name:'核验并登记资格'})).toBeDisabled();
  await expect(page.getByText('此材料尚无已保存的 Codex 审阅记录。',{exact:true})).toBeVisible();
  const started=await page.request.post(`/api/research/review-materials/${material.material_id}/reviews`,{data:{expected_material_fingerprint:material.material_fingerprint}});
  expect(started.status()).toBe(202);
  const run=await started.json();
  await expect.poll(async()=> (await(await page.request.get(`/api/research/technical-reviews/${run.run_id}`)).json()).status,{timeout:15000}).toBe('COMPLETE');
  await page.getByRole('button',{name:'刷新已保存材料与审阅'}).click();
  await page.getByLabel('已保存的 Codex 审阅记录').selectOption(run.run_id);
  await expect(page.getByText(/材料结论：INCONCLUSIVE/)).toBeVisible();
  await page.getByRole('button',{name:'核验并登记资格'}).click();
  await expect(page.getByRole('alert')).toBeVisible();
  const current=await(await page.request.get('/api/capabilities')).json();
  expect(current.formal_judgment).toBe('DISABLED');expect(current.formal_capabilities).toEqual([]);
  await page.getByRole('button',{name:'今天',exact:true}).click();
  await expect(page.getByText('交易判断未启用',{exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'历史记录',exact:true}).click();
  await page.getByRole('button',{name:'研究登记',exact:true}).click();
  await expect(page.getByRole('heading',{name:'研究登记与尝试',exact:true})).toBeVisible();
  await expect(page.getByText('登记保留事先设计和全部尝试。当前未授模型资格，未启动真实前向使用。',{exact:true})).toBeVisible();
  await page.screenshot({path:`../.scratch/roll-p0/evidence/final-review-fix/${process.env.ROLL_FINAL_STAGE}/settings-research.png`,fullPage:true});
  expect(failures).toEqual([]);
});
