import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const freeze='76286d80-4c5d-4262-b97d-ecb856f181f4';
test('saved METHOD report, isolated four curves, readonly export and legacy research link',async({page})=>{
  const original=await(await page.request.get('/api/research/shadow/'+freeze)).json();
  const source=await page.request.post('/api/data/requests',{data:{instruments:['SSE:600000'],groups:['QUOTE'],purpose:'OBSERVATION',start_date:'2026-10-07',end_date:'2026-10-07'}});
  expect(source.status()).toBe(201);
  expect((await page.request.post('/api/data/requests/'+(await source.json()).request_id+'/retrieve')).status()).toBe(200);
  const saved=await page.request.post('/api/account/valuations',{data:{baseline_account_version:1,origin_at:'2026-10-07T10:00:00+08:00',as_of:'2026-10-07T16:00:00+08:00'}});
  expect(saved.status()).toBe(201);
  const valuation=await saved.json();expect(valuation.facts.net_assets).toBe('103600.10');
  await page.goto('/#research='+freeze);
  await expect(page.getByRole('heading',{name:'历史记录',exact:true})).toBeVisible();
  const report=page.getByRole('region',{name:'保存的研究报告',exact:true});
  await expect(report).toBeVisible();
  await expect(report.getByRole('alert')).toHaveCount(0);
  await report.getByLabel('已保存实际估值',{exact:true}).selectOption(valuation.valuation_id);
  await expect(report.getByText(/已保存净资产 103600.10/)).toBeVisible();
  await expect(report.getByText('NOT_COMPARABLE',{exact:true})).toBeVisible();
  for(const label of ['ACTUAL','HISTORICAL','SHADOW','ACCOUNT_CONDITIONAL'])await expect(report.getByRole('heading',{name:label,exact:true})).toBeVisible();
  await expect(report.getByText('未经人工独立复核',{exact:false})).toBeVisible();
  await expect(report.getByRole('button',{name:/准备|买入|卖出|推送/})).toHaveCount(0);
  expect(await page.getByRole('navigation',{name:'主导航'}).getByRole('button').count()).toBe(5);
  const downloadPromise=page.waitForEvent('download');
  await report.getByRole('link',{name:'导出 JSON',exact:true}).click();
  const download=await downloadPromise;
  const exported=JSON.parse(readFileSync((await download.path())!,'utf8'));
  expect(exported.freeze_id).toBe(freeze);
  expect(exported.source_kind).toBe('RESEARCH');
  expect(exported.notification_allowed).toBe(false);
  expect(exported.actual.valuation).toEqual(valuation);
  expect(exported.platform.state).toEqual(original);
  expect(Object.keys(exported.namespaces).sort()).toEqual(['ACCOUNT_CONDITIONAL','ACTUAL','HISTORICAL','SHADOW']);
  await page.getByRole('button',{name:'今天',exact:true}).click();
  expect((await(await page.request.get('/api/actions/current')).json()).decisions).toEqual([]);
  expect((await page.request.post('/api/formal/evaluate',{data:{}})).status()).toBe(403);
  await page.getByRole('button',{name:'历史记录',exact:true}).click();
  await expect(report).toBeVisible();
  await expect(report.getByText('NOT_COMPARABLE',{exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/reports-open.png',fullPage:true});
  await page.getByRole('button',{name:'研究登记',exact:true}).click();
  await expect(report).toHaveCount(0);
  expect(await(await page.request.get('/api/research/shadow/'+freeze)).json()).toEqual(original);
  await page.screenshot({path:'test-results/reports-history.png',fullPage:true});
});
