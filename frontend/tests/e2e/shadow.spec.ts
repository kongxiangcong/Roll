import {expect,test} from '@playwright/test';
import {resolve} from 'node:path';
test('full freeze and continuous research remain separated from actual and conditional accounts',async({page})=>{
  test.setTimeout(180000);
  const development=await (await page.request.post('/api/research/development-runs',{timeout:120000})).json();
  expect(development.status).toBe('ENGINEERING_COMPLETE');
  const pid=development.protocol_id;
  const model=await (await page.request.get(`/api/research/models/${development.model_run_id}`)).json();
  const high=model.calibration_predictions.find((p:{logit:number;observation_date:string})=>1/(1+Math.exp(-p.logit-model.calibrator.intercept_shift))>=.6);
  await page.goto('/');await page.getByRole('button',{name:'历史记录',exact:true}).click();await page.getByRole('button',{name:'研究登记',exact:true}).click();
  await page.getByRole('button',{name:`查看协议 ${pid.slice(0,8)}`,exact:true}).click();
  const panel=page.getByRole('region',{name:'研究政策与连续影子'});
  await panel.getByRole('button',{name:'冻结完整实验与影子基线',exact:true}).click();
  await expect(panel.getByText(/完整实验已冻结 · METHOD_CASE/)).toBeVisible();
  await panel.getByLabel('研究交易日').fill(high.observation_date);
  await panel.getByRole('button',{name:'归档历史研究机会',exact:true}).click();
  await expect(panel.getByText('待推进 1 项',{exact:false})).toBeVisible();
  await panel.getByRole('button',{name:'推进连续影子',exact:true}).click();
  await expect(panel.getByRole('article',{name:'SHADOW 连续影子'})).toContainText('版本 1');
  const saved=await (await page.request.get(`/api/research/protocols/${pid}/complete-freezes`)).json();
  const frozen=saved[0];
  await panel.getByRole('button',{name:'保存一次账户条件诊断',exact:true}).click();
  await expect(panel.getByRole('article',{name:'ACCOUNT_CONDITIONAL 一次账户条件诊断'})).toContainText('1 项');
  await panel.getByRole('button',{name:'重放连续影子',exact:true}).click();
  await expect(panel.getByRole('status')).toContainText('连续影子重放一致 · 联网 0 次');
  for(const name of ['ACTUAL 真实账户','HISTORICAL 历史诊断','SHADOW 连续影子','ACCOUNT_CONDITIONAL 一次账户条件诊断'])await expect(panel.getByRole('article',{name,exact:true})).toBeVisible();
  await expect(panel.getByRole('button',{name:/执行|买入|确认交易/})).toHaveCount(0);
  expect((await (await page.request.get('/api/account')).json()).version).toBe(0);
  expect((await (await page.request.get(`/api/research/protocols/${pid}`)).json()).forward_started_at).toBeNull();
  expect((await (await page.request.get(`/api/research/shadow/${frozen.freeze_id}`)).json()).revision).toBe(1);
  await panel.screenshot({path:resolve('../.scratch/roll-p0/evidence/20/shadow-isolation.png')});
});
