import {expect,test} from '@playwright/test';
import {resolve} from 'node:path';
test('user reviews exact frozen materials and exports a preliminary package with separate current status',async({page})=>{
  test.setTimeout(180000);
  const run=await (await page.request.post('/api/research/development-runs',{timeout:120000})).json();
  const model=await (await page.request.get(`/api/research/models/${run.model_run_id}`)).json();
  const high=model.calibration_predictions.find((p:{logit:number;observation_date:string})=>1/(1+Math.exp(-p.logit-model.calibrator.intercept_shift))>=.6);
  await page.goto('/');await page.getByRole('button',{name:'历史记录',exact:true}).click();await page.getByRole('button',{name:'研究登记',exact:true}).click();
  await page.getByRole('button',{name:`查看协议 ${run.protocol_id.slice(0,8)}`,exact:true}).click();
  const shadow=page.getByRole('region',{name:'研究政策与连续影子'});
  await shadow.getByRole('button',{name:'冻结完整实验与影子基线',exact:true}).click();
  await expect(shadow.getByText(/完整实验已冻结/)).toBeVisible();
  await shadow.getByLabel('研究交易日').fill(high.observation_date);
  await shadow.getByRole('button',{name:'归档历史研究机会',exact:true}).click();
  await expect(shadow.getByText(/待推进 1 项/)).toBeVisible();
  await shadow.getByRole('button',{name:'推进连续影子',exact:true}).click();
  await expect(shadow.getByRole('article',{name:'SHADOW 连续影子'})).toContainText('版本 1',{timeout:30000});
  const validation=page.getByRole('region',{name:'自动验证与门槛证据'});
  await validation.getByRole('button',{name:'检查当前验证证据',exact:true}).click();
  const review=page.getByRole('region',{name:'模型技术审阅与验证交付'});
  await review.getByRole('button',{name:'审阅冻结材料',exact:true}).click();
  await expect(review.getByText('当前技术审阅 COMPLETE',{exact:true})).toBeVisible({timeout:30000});
  await expect(review).toContainText('真实验证交付未完成');
  await expect(review).toContainText('经自动验证与模型技术审阅，未经人工独立复核');
  await expect(validation).toContainText('记录时：');
  await review.getByRole('button',{name:'导出验证包',exact:true}).click();
  await expect(review.getByRole('link',{name:'下载验证包',exact:true})).toBeVisible();
  await page.reload();await page.getByRole('button',{name:'历史记录',exact:true}).click();await page.getByRole('button',{name:'研究登记',exact:true}).click();
  await page.getByRole('button',{name:`查看协议 ${run.protocol_id.slice(0,8)}`,exact:true}).click();
  await expect(page.getByRole('region',{name:'模型技术审阅与验证交付'}).getByText('当前技术审阅 COMPLETE',{exact:true})).toBeVisible();
  await expect(page.getByRole('region',{name:'模型技术审阅与验证交付'})).toContainText('真实验证交付未完成');
  await expect(page.getByRole('region',{name:'模型技术审阅与验证交付'})).toContainText('未经人工独立复核');
  expect((await (await page.request.get('/api/account')).json()).version).toBe(0);
  await page.getByRole('region',{name:'模型技术审阅与验证交付'}).screenshot({path:resolve('../.scratch/roll-p0/evidence/23/technical-review.png')});
});
