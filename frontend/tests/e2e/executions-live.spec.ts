import {expect,test} from '@playwright/test';
import {resolve} from 'node:path';
test.skip(process.env.ROLL_EXECUTION_LIVE!=='1','Requires actual preserved17 partitions plus independently tagged METHOD18 HTTP execution, not fixture replacement');
test('real historical execution support retains120 unknown cases, zero real training and no user account authority',async({page})=>{
  const datasets=await (await page.request.get('/api/research/datasets')).json();
  const actual=datasets.find((d:{source_evidence_kind:string})=>d.source_evidence_kind==='REAL_ACQUISITION');
  const protocols=await (await page.request.get('/api/research/protocols')).json();
  const protocol=protocols.find((p:{dataset_id:string})=>p.dataset_id===actual.dataset_id);
  await page.goto('/');await page.getByRole('button',{name:'历史记录',exact:true}).click();await page.getByRole('button',{name:'研究登记',exact:true}).click();
  await expect(page.getByRole('navigation',{name:'主导航'}).getByRole('button')).toHaveCount(5);
  await page.getByRole('button',{name:`查看协议 ${protocol.protocol_id.slice(0,8)}`,exact:true}).click();
  const panel=page.getByRole('region',{name:'日线执行与成熟标签'});
  await expect(panel.getByText(/保留记录 120.*真实训练可用 0.*METHOD 情景 0/)).toBeVisible();
  await expect(panel.getByText('UNSCORABLE: 120',{exact:true})).toBeVisible();
  await expect(panel.getByText(/HISTORICAL_STATUS_UNKNOWN.*COMPANY_ACTIONS_UNKNOWN/).first()).toBeVisible();
  expect((await (await page.request.get('/api/account')).json()).version).toBe(0);
  const support=await (await page.request.get(`/api/research/protocols/${protocol.protocol_id}/execution-support`)).json();
  expect(support.eligible_for_training_count).toBe(0);expect(support.records.every((r:{result:{label:null;net_pnl_yuan:null}})=>r.result.label===null&&r.result.net_pnl_yuan===null)).toBeTruthy();
  await panel.screenshot({path:resolve('../.scratch/roll-p0/evidence/18/18-real-unknown.png')});
});
test('method execution view shows immutable maturity, interval and fee scenarios, saves and offline-replays same inputs',async({page})=>{
  const datasets=await (await page.request.get('/api/research/datasets')).json();
  const method=datasets.find((d:{source_evidence_kind:string})=>d.source_evidence_kind==='METHOD_CASE');
  const protocols=await (await page.request.get('/api/research/protocols')).json();
  const protocol=protocols.find((p:{dataset_id:string})=>p.dataset_id===method.dataset_id);
  await page.goto('/');await page.getByRole('button',{name:'历史记录',exact:true}).click();await page.getByRole('button',{name:'研究登记',exact:true}).click();
  await page.getByRole('button',{name:`查看协议 ${protocol.protocol_id.slice(0,8)}`,exact:true}).click();
  const panel=page.getByRole('region',{name:'日线执行与成熟标签'});
  await expect(panel.getByText(/HISTORICAL · METHOD_CASE/)).toBeVisible();
  await expect(panel.getByText(/净损益区间/).first()).toBeVisible();
  await expect(panel.getByText(/真实训练可用 0/)).toBeVisible();
  await panel.getByText('历史评估时点与方法数量',{exact:true}).click();
  await panel.getByLabel('标签评估时点（带时区）').fill('2026-01-06T16:00:00+08:00');await panel.getByLabel('计划股数').fill('100');
  await panel.getByRole('button',{name:'保存日线模拟',exact:true}).click();
  const all=panel.getByRole('button',{name:'查看全部执行记录',exact:true});if(await all.count())await all.click();
  await expect(panel.getByText(/2026-01-05 · DEVELOPMENT · IMMATURE/)).toBeVisible();
  const before=await (await page.request.get(`/api/research/protocols/${protocol.protocol_id}/execution-support`)).json();
  const immature=before.records.find((r:{result:{label_status:string}})=>r.result.label_status==='IMMATURE');
  expect(immature.result.label).toBeNull();expect(immature.result.eligible_for_training).toBeFalsy();
  await panel.getByRole('button',{name:`原输入离线重放 ${immature.execution_id.slice(0,8)}`,exact:true}).click();
  await expect(panel.getByRole('status')).toContainText('与原结果一致 · 联网 0 次');
  const original=await (await page.request.get(`/api/research/executions/${immature.execution_id}`)).json();
  await panel.getByRole('button',{name:`追加当前复评 ${immature.execution_id.slice(0,8)}`,exact:true}).click();await expect(panel.getByRole('status')).toContainText('原结果保留');
  expect(await (await page.request.get(`/api/research/executions/${immature.execution_id}`)).json()).toEqual(original);
  expect((await (await page.request.get('/api/account')).json()).version).toBe(0);
  await expect(page.getByRole('navigation',{name:'主导航'}).getByRole('button')).toHaveCount(5);
  await panel.screenshot({path:resolve('../.scratch/roll-p0/evidence/18/18-method.png')});
});
