import {expect,test} from '@playwright/test';
test('prepare and externally pending partial fill are distinct from actual account facts',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'核验当前动作',exact:true}).click();
  await expect(page.getByText('当前没有有效正式动作',{exact:true})).toBeVisible();
  await expect(page.getByRole('alert')).toHaveCount(0);
  const at=new Date(Date.now()-1000).toISOString();
  const b=await(await page.request.post('/api/account/drafts',{data:{kind:'BASELINE',expected_account_version:0,payload:{effective_at:'2026-10-07T10:00:00+08:00',source:'METHOD browser',cash_balance:'100000.10',broker_available:'90000.10',broker_frozen:'10000.00',withdrawable:null,positions:[],permission_profile:[{market:'SSE',board:'MAIN',status:'OPEN',basis:'METHOD'}]}}})).json();
  await page.request.post('/api/account/confirm',{data:{draft_id:b.draft_id,idempotency_key:'baseline'}});
  const d=await(await page.request.post('/api/account/drafts',{data:{kind:'ACCOUNT_DECLARATION',expected_account_version:1,payload:{effective_at:at,source:'METHOD',record_id:'declaration',scope:['TRADES','ORDERS','CASH','EQUITY'],changes:'NONE',basis:'METHOD'} }})).json();
  await page.request.post('/api/account/confirm',{data:{draft_id:d.draft_id,idempotency_key:'declaration'}});
  for(const instrument of ['SSE:600000','SSE:600001']){
    const listing=await(await page.request.get('/api/market/list')).json();
    expect((await page.request.post('/api/market/watch',{data:{instrument,operation:'ADD',expected_list_version:listing.version}})).status()).toBe(200);
  }
  const authorization={scope_kind:'ACCOUNT',scope_id:'account-1',purpose:'METHOD',capital_amount:'100000.00',total_exposure:'60000.00',single_exposure:'40000.00',cash_reserve:'40000.00',loss_threshold:'5000.00',effective_at:'2026-10-07T10:00:00+08:00',basis:'METHOD',enabled:true};
  await page.request.post('/api/funding/confirm',{data:{expected_version:0,idempotency_key:'funding',authorization}});
  const proposal=await(await page.request.get('/api/capabilities/proposal?material_id=method-material&review_run_id=method-codex-review')).json();
  const grant=await page.request.post('/api/capabilities/grants',{data:{...proposal,allowed_actions:['BUY'],idempotency_key:'grant',basis:'METHOD'}});
  expect(grant.status()).toBe(201);
  await page.reload();
  await page.getByRole('button',{name:'核验当前动作',exact:true}).click();
  await expect(page.getByText('SSE:600000 · 买入',{exact:true})).toBeVisible();
  await expect(page.getByText('当前 0 股 → 目标 200 股')).toBeVisible();
  await expect(page.getByText(/当前报价截至.*累计成交量 12345/)).toBeVisible();
  await expect(page.getByText(/最近完整日线预测截至.*20 个交易日/)).toBeVisible();
  await expect(page.getByText('METHOD 工程样例，不能用于真实正式建议。')).toBeVisible();
  await expect(page.getByText('后续价格和成交结果存在不确定性，实际成交须由你确认入账。')).toBeVisible();
  const before=await(await page.request.get('/api/account')).json();
  await page.getByLabel('准备价格 SSE:600000').fill('140.00');
  await page.getByRole('button',{name:'准备操作',exact:true}).click();
  const intentCard=page.getByRole('article',{name:'执行意向 SSE:600000',exact:true});
  await expect(intentCard.getByText('已同步 0 股 · 剩余待核 200 股 · 临时占用 30005.00 元')).toBeVisible();
  expect(await(await page.request.get('/api/account')).json()).toEqual(before);
  await intentCard.getByText('记录自行操作结果',{exact:true}).click();
  await intentCard.getByLabel('外部委托标识',{exact:true}).fill('browser-order');
  await intentCard.getByLabel('券商可用资金中的占用').selectOption('CONFIRMED_REFLECTED');
  await intentCard.getByRole('button',{name:'已自行操作，待同步',exact:true}).click();
  await expect(intentCard.getByText('SSE:600000 · 已操作待同步',{exact:true})).toBeVisible();
  expect((await(await page.request.get('/api/intents')).json()).unreflected_reservation_yuan).toBe('0.00');
  await page.screenshot({path:'test-results/intents-pending.png',fullPage:true});
  const value=(await(await page.request.get('/api/intents')).json()).intents[0];
  await page.getByRole('button',{name:'同步账户',exact:true}).click();
  await page.getByRole('button',{name:'同步实际成交',exact:true}).click();
  await page.getByLabel('成交证券代码',{exact:true}).fill('600000');
  await page.getByLabel('实际成交数量',{exact:true}).fill('100');
  await page.getByLabel('原始成交价格（元）',{exact:true}).fill('140.00');
  await page.getByLabel('分笔成交标识',{exact:true}).fill('browser-partial');
  await page.getByLabel('券商委托标识（可选）',{exact:true}).fill('browser-order');
  await page.getByLabel('实际费用（元）',{exact:true}).fill('5.00');
  await page.getByLabel('费用依据',{exact:true}).fill('METHOD broker fee');
  await page.getByLabel('成交后已核对券商可用资金（元，可空）',{exact:true}).fill('76000.10');
  await page.getByLabel('关联数量 '+value.intent_id,{exact:true}).fill('100');
  await page.getByRole('button',{name:'预览成交差异',exact:true}).click();
  await expect(page.getByText('确认前的资金与持仓差异',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'确认实际成交',exact:true}).click();
  await expect(page.getByText('实际成交已确认，回执已保存',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'回到今天',exact:true}).click();
  await expect(page.getByText('已同步 100 股 · 剩余待核 100 股 · 临时占用 15002.50 元')).toBeVisible();
  await expect(page.getByText('当前没有有效正式动作',{exact:true})).toBeVisible();
  await expect(page.getByText(/送达与已读未知/)).toBeVisible();
  const after=await(await page.request.get('/api/account')).json();
  expect(after.positions[0].quantity).toBe('100');
  expect(after.cash_balance).toBe('85995.10');
  await page.screenshot({path:'test-results/intents-partial.png',fullPage:true});
});
