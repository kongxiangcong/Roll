import {expect,test} from '@playwright/test';
import {resolve} from 'node:path';
test.skip(process.env.ROLL_RESEARCH_LIVE!=='1','Requires previously preserved actual public-source registration, never a synthetic data substitute');
test('history research shows actual limited coverage, all attempts, audit and linked immutable versions without granting capability',async({page})=>{
  const protocols=await (await page.request.get('/api/research/protocols')).json();
  const original=protocols.find((p:{predecessor_id:string|null})=>!p.predecessor_id);
  expect(original).toBeTruthy();
  await page.goto('/');await page.getByRole('button',{name:'历史记录',exact:true}).click();
  await expect(page.getByRole('navigation',{name:'主导航'}).getByRole('button')).toHaveCount(5);
  await page.getByRole('button',{name:'研究登记',exact:true}).click();
  await expect(page.getByText(/181 个交易日.*2026-01-05.*2026-09-30/)).toBeVisible();
  await page.getByRole('button',{name:`查看协议 ${original.protocol_id.slice(0,8)}`,exact:true}).click();
  await expect(page.getByText(/ENGINEERING_REPLAY.*FAILED/)).toBeVisible();
  await expect(page.getByText(/ENGINEERING_REPLAY.*ABORTED/)).toBeVisible();
  await expect(page.getByText(/ENGINEERING_REPLAY.*INTERRUPTED/)).toBeVisible();
  await expect(page.getByText(/当前成熟封存标签上界 1.*INSUFFICIENT_FOR_CONFIRMATORY_PASS/)).toBeVisible();
  await expect(page.getByText(/结论 尚未判定.*封存独立性 UNPROVEN.*NOT_GRANTED.*前向起点 尚未启动/)).toBeVisible();
  await page.getByRole('button',{name:'检查完整冻结',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('MODEL_ARTIFACT_MISSING');
  await page.getByText('封存输入访问',{exact:true}).click();await page.getByLabel('访问依据').fill('Chrome工程输入边界核验，不计算标签/候选结果');
  await page.getByRole('button',{name:'访问封存输入并登记',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('非确认性PASS查看');
  await page.getByRole('button',{name:'登记关联后继版本',exact:true}).click();
  await expect(page.getByRole('heading',{name:'与前序比较'})).toBeVisible();
  const current=await (await page.request.get('/api/research/protocols')).json();
  expect(current[0].predecessor_id).toBe(original.protocol_id);
  expect(await (await page.request.get('/api/research/protocols/'+original.protocol_id)).json()).toEqual(original);
  expect((await (await page.request.get('/api/account')).json()).version).toBe(0);
  await page.screenshot({path:resolve(process.env.ROLL_RESEARCH_SCREENSHOT??'../.scratch/roll-p0/evidence/17/17-research.png'),fullPage:true});
});
