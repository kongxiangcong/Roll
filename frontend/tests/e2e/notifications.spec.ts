import {test,expect} from '@playwright/test';

test('station explicit read, old link current state and disabled private channel settings',async({page})=>{
  const pause=await page.request.post('/api/capabilities/lifecycle',{data:{scope:'ALL_MONITOR',state:'SUSPENDED',reason_code:'USER_PAUSE',reason:'用户暂停监控，事实同步仍允许',expected_version:0,idempotency_key:'browser-pause'}});
  expect(pause.status()).toBe(200);
  const original=(await(await page.request.get('/api/notifications')).json()).notifications[0];
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'通知',exact:true})).toBeVisible();
  const panel=page.getByRole('region',{name:'通知',exact:true});
  await expect(panel.getByText('需要同步/恢复',{exact:true})).toBeVisible();
  await expect(panel.getByText('未配置外部渠道，需打开查看',{exact:true})).toBeVisible();
  expect((await(await page.request.get('/api/notifications')).json()).notifications[0].read_at).toBeNull();
  await panel.getByRole('button',{name:'标为已读',exact:true}).click();
  await expect(panel.getByText('站内已读',{exact:true})).toBeVisible();
  const receipt=await pause.json();
  expect((await page.request.post('/api/capabilities/lifecycle',{data:{scope:'ALL_MONITOR',state:'ACTIVE',reason_code:'USER_PAUSE',reason:'恢复用户主动暂停',resume_event_id:receipt.event_id,expected_version:1,idempotency_key:'browser-resume'}})).status()).toBe(200);
  await page.goto('/#notification='+original.notification_id);
  await expect(page.getByText('已被后续状态替代',{exact:true})).toBeVisible();
  await expect(page.getByText('外部送达与已读未知',{exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'设置',exact:true}).click();
  const settings=page.getByRole('region',{name:'通知渠道',exact:true});
  await expect(settings.getByText('默认关闭；保存配置不会发送验收消息。',{exact:true})).toBeVisible();
  await settings.getByLabel('服务器地址',{exact:true}).fill('https://ntfy.example.test');
  await settings.getByLabel('主题',{exact:true}).fill('method-topic');
  await settings.getByLabel('应用地址',{exact:true}).fill('http://127.0.0.1:5173');
  await settings.getByLabel('认证令牌',{exact:true}).fill('SYNTHETIC_BROWSER_CANARY');
  await settings.getByRole('button',{name:'保存渠道配置',exact:true}).click();
  await expect(settings.getByText('认证已配置',{exact:true})).toBeVisible();
  await expect(settings.getByLabel('认证令牌',{exact:true})).toHaveValue('');
  expect(JSON.stringify(await(await page.request.get('/api/notification-channel')).json())).not.toContain('SYNTHETIC_BROWSER_CANARY');
  expect((await(await page.request.get('/api/notifications/audit')).json()).transmission_attempts).toBe(0);
  await settings.getByLabel('清除已保存认证',{exact:true}).check();
  await settings.getByRole('button',{name:'保存渠道配置',exact:true}).click();
  await expect(settings.getByText('未配置认证',{exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/notifications-settings.png',fullPage:true});
});
