import {test,expect} from '@playwright/test';
test('METHOD linked preregistration to snapshot and engineering preflight, with shared budget refusal',async({page,request})=>{
 const protocols=await (await request.get('/api/research/protocols')).json();const parent=protocols.find((p:{predecessor_id:string|null})=>p.predecessor_id===null);
 const attempts=await (await request.get('/api/research/protocols/'+parent.protocol_id+'/attempts')).json();expect(attempts).toHaveLength(0);
 await page.goto('/');await page.getByRole('button',{name:'历史记录',exact:true}).click();await page.getByRole('button',{name:'研究登记',exact:true}).click();
 await page.getByText('财务情绪特征与消融协议',{exact:true}).click();await page.getByRole('button',{name:'查询特征协议与快照',exact:true}).click();
 await page.getByLabel('特征前序实验',{exact:true}).selectOption(parent.protocol_id);
 await expect(page.getByText(/剩余额度 1/)).toBeVisible();
 for(const label of ['原量价基线','加情绪','财务与情绪组合'])await page.getByLabel(label,{exact:true}).uncheck();
 await page.getByRole('button',{name:'登记关联特征协议',exact:true}).click();
 await expect(page.getByText(/协议已登记 · FINANCIAL · 主要候选 FINANCIAL/)).toBeVisible();
 await expect(page.getByText(/剩余额度 0/)).toBeVisible();
 await page.getByRole('button',{name:'保存可得特征快照',exact:true}).click();
 await expect(page.getByRole('region',{name:'可得特征快照'}).getByText(/METHOD工程样例/)).toBeVisible();
 await page.getByRole('button',{name:'保存特征工程预检',exact:true}).click();
 await expect(page.getByRole('region',{name:'特征工程预检'}).getByText(/工程契约成立 · 真实拟合未准入/)).toBeVisible();
 await page.getByText('查看拟合仍缺条件',{exact:true}).click();
 await expect(page.getByText('FEATURE_FIT_EXECUTOR_AND_TRAINING_AUTHORITY_TICKET23_REQUIRED',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'登记关联特征协议',exact:true}).click();
 await expect(page.getByRole('alert').filter({hasText:'家族拟合额度不足'})).toBeVisible();
 await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:'../.scratch/roll-capability-expansion/evidence/22-features/method-mobile.png',fullPage:true});
 expect(await (await request.get('/api/research/protocols/'+parent.protocol_id)).json()).toEqual(parent);
 expect(await (await request.get('/api/research/protocols/'+parent.protocol_id+'/attempts')).json()).toEqual(attempts);
 expect((await (await request.get('/api/account')).json()).version).toBe(0);
});
