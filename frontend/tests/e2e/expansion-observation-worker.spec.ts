import {test,expect} from '@playwright/test';
test('real online receipts, source pause, queued cancellation and station-only settings',async({page,request})=>{
 let executions=0;page.on('request',r=>{if(r.method()==='POST'&&/\/(classify|collect)$/.test(new URL(r.url()).pathname))executions++;});
 const channel=await (await request.get('/api/notification-channel')).json();
 const before=await (await request.get('/api/observation-updates/SSE:600362')).json();
 expect(before.observations).toHaveLength(2);expect(before.observations.every((o:{evidence_kind:string})=>o.evidence_kind==='REAL_SAVED_OBSERVATION')).toBeTruthy();
 await page.goto('/');await page.getByRole('button',{name:'持仓与关注',exact:true}).click();
 await page.getByText('日常财报新闻观察',{exact:true}).click();await page.getByRole('button',{name:'查询日常观察状态',exact:true}).click();
 const panel=page.getByRole('region',{name:'日常观察状态'});
 await expect(panel.getByText(/日常观察已启用/)).toBeVisible();
 await expect(panel.getByText(/任务 3 条；观察 2 个/)).toBeVisible();
 await expect(panel.getByText(/已复用同输入观察/)).toBeVisible();
 await page.getByRole('button',{name:'暂停日常观察',exact:true}).click();
 await expect(panel.getByText(/日常观察已暂停/)).toBeVisible();
 await expect(page.getByRole('button',{name:'请求新闻观察更新',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'暂停AKShare 东财单股新闻',exact:true}).click();
 await expect(panel.getByText(/AKShare 东财单股新闻 · 来源已暂停/)).toBeVisible();
 await page.getByRole('button',{name:'启用日常观察',exact:true}).click();
 await page.getByRole('button',{name:'请求财务观察更新',exact:true}).click();
 await expect(panel.getByText(/FINANCIAL · QUEUED/)).toBeVisible();
 await panel.getByRole('button',{name:/取消观察任务/}).click();
 await expect(panel.getByText(/FINANCIAL · CANCELLED/)).toBeVisible();
 await panel.getByText('查看原worker与离线覆盖回执',{exact:true}).click();
 await expect(panel.getByText(/NORMAL_OFFLINE_NO_COVERAGE_PROMISED/).first()).toBeVisible();
 await panel.locator('summary').filter({hasText:'NEWS · 实际保存来源观察'}).click();
 await expect(panel.getByText(/已保存新闻 22 条.*本次仅事实观察/)).toBeVisible();
 await page.screenshot({path:'../.scratch/roll-capability-expansion/evidence/18-worker/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:'../.scratch/roll-capability-expansion/evidence/18-worker/mobile.png',fullPage:true});
 expect((await (await request.get('/api/observation-updates/SSE:600362')).json()).observations).toEqual(before.observations);
 expect(await (await request.get('/api/notification-channel')).json()).toEqual(channel);
 expect((await (await request.get('/api/account')).json()).version).toBe(0);expect(executions).toBe(0);
});
